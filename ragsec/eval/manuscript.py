_TABLE_INPUT = re.compile(r"^\\input\{\\paperdir tables/(tab_[a-z_]+)\}\s*$", re.MULTILINE)
_FIGURE_PATH = re.compile(r"\{\\paperdir figures/")
_MACRO = re.compile(r"^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", re.MULTILINE)


def _strip_comments(text: str) -> str:
    """Drop whole-line source comments.

    These are working notes rather than manuscript content, and the horizontal rules among
    them are runs of hyphens that would otherwise trip the em-dash check on the output.
    """
    return "\n".join(
        line for line in text.splitlines() if not line.lstrip().startswith("%")
    )


def inline_tables(body: str, tables_dir: Path) -> tuple[str, int]:
    """Replace every table \\input with the table's own LaTeX."""
    count = 0

    def substitute(match: re.Match[str]) -> str:
        nonlocal count
        path = tables_dir / f"{match.group(1)}.tex"
        if not path.exists():
            raise FileNotFoundError(f"table not generated: {path}")
        count += 1
        return path.read_text(encoding="utf-8").rstrip()

    return _TABLE_INPUT.sub(substitute, body), count


def build(
    project_root: Path,
    out_path: Path,
    journal: str = JOURNAL,
) -> dict[str, int]:
    """Write the flattened submission file and return a small summary."""
    paper = project_root / "paper"
    body = _strip_comments((paper / "body.tex").read_text(encoding="utf-8")).strip()
    body, n_tables = inline_tables(body, paper / "tables")
    body = _FIGURE_PATH.sub("{figures/", body)

    macros_src = (paper / "tables" / "macros.tex").read_text(encoding="utf-8")
    macros = _MACRO.findall(macros_src)
    macro_block = (
        "%% Result values, generated from results/paper/*.jsonl by `ragsec figures`.\n"
        "%% Every number quoted in the text below resolves through one of these.\n"
        + "\n".join(f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros)
        + "\n"
    )

    bibliography = _strip_comments(
        (paper / "bibliography.tex").read_text(encoding="utf-8")
    ).strip()

    preamble = PREAMBLE.replace("JOURNAL", journal, 1).replace("ABSTRACT", ABSTRACT, 1)
    # The result definitions belong in the preamble, before \begin{document}, which PREAMBLE
    # therefore stops short of.
    document = "\n".join(
        [preamble, macro_block, "\\begin{document}", "", body,
         BACK_MATTER, bibliography, FOOTER]
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(document, encoding="utf-8")
    return {
        "tables_inlined": n_tables,
        "macros_inlined": len(macros),
        "bibitems": bibliography.count("\\bibitem"),
        "lines": document.count("\n") + 1,
        "em_dashes": document.count("---"),
    }
